CREATE DATABASE IF NOT EXISTS jobbridge CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE jobbridge;
CREATE TABLE IF NOT EXISTS users (
 id BIGINT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(120) NOT NULL,
 email VARCHAR(190) NOT NULL UNIQUE, password_hash VARCHAR(255) NOT NULL,
 role VARCHAR(20) NOT NULL DEFAULT 'seeker', company_name VARCHAR(180),
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS jobs (
 id BIGINT AUTO_INCREMENT PRIMARY KEY, company_id BIGINT NOT NULL,
 title VARCHAR(180) NOT NULL, location VARCHAR(180) NOT NULL,
 job_type VARCHAR(60) NOT NULL DEFAULT 'Full-time', description TEXT NOT NULL,
 requirements TEXT, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT fk_jobs_company FOREIGN KEY(company_id) REFERENCES users(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS applications (
 id BIGINT AUTO_INCREMENT PRIMARY KEY, job_id BIGINT NOT NULL, seeker_id BIGINT NOT NULL,
 cover_letter TEXT, status VARCHAR(30) NOT NULL DEFAULT 'Submitted',
 applied_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 UNIQUE KEY unique_application(job_id,seeker_id),
 CONSTRAINT fk_app_job FOREIGN KEY(job_id) REFERENCES jobs(id) ON DELETE CASCADE,
 CONSTRAINT fk_app_seeker FOREIGN KEY(seeker_id) REFERENCES users(id) ON DELETE CASCADE
);
